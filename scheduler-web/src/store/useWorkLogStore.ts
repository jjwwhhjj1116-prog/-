export interface DailyWorkLog {
  reportMode?:'DAILY'|'TASK';
  serverRevision?:number;
  id: string;
  date: string; // YYYY-MM-DD
  userId: string;
  userName: string;
  userPosition: string;
  department: Department;
  items: WorkLogItem[];
  overallNotes: string;
  autoGeneratedDay?:string;
  autoReportedAt?:string;
  // 2단 결재 상태: 작성중(DRAFT) -> 1차 팀장검토대기(SUBMITTED_LEADER) -> 2차 실장최종승인(APPROVED_FINAL)
  approvalStatus: 'DRAFT' | 'SUBMITTED_LEADER' | 'APPROVED_FINAL' | 'SUBMITTED_PM' | 'APPROVED_PM';
  authorSignature: {
    signed: boolean;
    name: string;
    signedAt?: string;
  };
  // 1차 팀장 검토 (마감팀: 김재헌 팀장, 구조팀: 신동헌 팀장)
  leaderReview: ApprovalSign;
  // 2차 실장 최종 승인 (마감팀: 조한빈 실장, 구조팀: 장범선 실장)
  chiefApproval: ApprovalSign;
  // 레거시 호환 필드
  pmApproval?: ApprovalSign;
  teamLeaderApproval?: ApprovalSign;
  createdAt: string;
  updatedAt: string;
}

const STORAGE_KEY = 'concost_daily_worklogs_v2';

const loadInitialWorkLogs = (): DailyWorkLog[] => {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved) {
      const parsed = JSON.parse(saved);
      try{if(!localStorage.getItem('studio-legacy-worklogs-v1'))localStorage.setItem('studio-legacy-worklogs-v1',saved);}catch{/* 기존 자료는 유지 */}
      if (Array.isArray(parsed)) {
        return parsed.map((item: any) => {
          const dept = (item.department || '마감팀') as Department;
          const line = TEAM_APPROVAL_LINES[dept] || TEAM_APPROVAL_LINES.마감팀;
          return {
            ...item,
            leaderReview: item.leaderReview || item.pmApproval || { approved: false, name: line.leader.name },
            chiefApproval: item.chiefApproval || item.teamLeaderApproval || { approved: false, name: line.chief.name }
          };
        });
      }
    }
  } catch (e) {
    console.error('Failed to load worklogs from localStorage', e);
  }
  return [];
};

interface WorkLogState {
  workLogs: DailyWorkLog[];
  selectedWorkLogId: string | null;
  setSelectedWorkLogId: (id: string | null) => void;
  saveWorkLog: (log: DailyWorkLog) => Promise<void>;
  readWorkLog: (id: string, revision: number) => Promise<boolean>;
  deleteWorkLog: (id: string) => Promise<void>;
  // 1단계: 작성자 -> 해당 팀 팀장에게 결재 상신 (마감팀: 김재헌 팀장, 구조팀: 신동헌 팀장)
  submitApprovalToLeader: (id: string) => Promise<void>;
  // 2단계: 해당 팀 실장 최종 결재 승인 (마감팀: 조한빈 실장, 구조팀: 장범선 실장) -> 일정표에 실시간 반영 및 저장
  approveFinalByChief: (id: string, chiefName?: string) => Promise<void>;
  // 이전 호환 메서드 (하위호환 유지)
  submitApprovalToPm: (id: string) => Promise<void>;
  approveByPm: (id: string, pmName: string) => Promise<void>;
  approveFinalByLeader: (id: string, leaderName: string) => Promise<void>;
  // 팀별 일정표에서 특정 인원의 오늘 업무 자동 추출 (정밀 연계)
  generateItemsFromSchedule: (userName: string, _dateStr: string, projects: Project[]) => WorkLogItem[];
}

async function saveServerLog(log:DailyWorkLog){
  const actor=useAuthStore.getState().currentUser;if(!actor)throw Error('로그인 후 업무일지를 저장하세요.');
  const selectedWorkLogId=useWorkLogStore.getState().selectedWorkLogId;
 const {log:saved}=await studioApi(`worklogs/${encodeURIComponent(log.id)}`,'PUT',{log,revision:log.serverRevision});
  if(actor!==useAuthStore.getState().currentUser)throw Error('이전 계정의 저장은 완료되었습니다. 계정이 변경되어 현재 화면 반영과 후속 작업을 중단했습니다.');
  const current=useWorkLogStore.getState().workLogs.find(w=>w.id===saved.id);
  if(typeof current?.serverRevision==='number'&&typeof saved.serverRevision==='number'&&current.serverRevision>saved.serverRevision)throw Error('서버 저장은 완료되었습니다. 더 최신 일지가 확인되어 현재 화면 반영과 후속 작업을 중단했습니다.');
 useWorkLogStore.setState(state=>({workLogs:[saved,...state.workLogs.filter(w=>w.id!==saved.id)],selectedWorkLogId:state.selectedWorkLogId===selectedWorkLogId?saved.id:state.selectedWorkLogId}));
}
async function logAction(id:string,action:string){
  const actor=useAuthStore.getState().currentUser;if(!actor)throw Error('로그인 후 업무일지를 처리하세요.');
 const target=useWorkLogStore.getState().workLogs.find(w=>w.id===id);if(!target?.serverRevision)throw Error('먼저 중앙 서버에 일지를 저장하세요.');
 const {log}=await studioApi(`worklogs/${encodeURIComponent(id)}/${action}`,'POST',{revision:target.serverRevision});
  if(actor!==useAuthStore.getState().currentUser)throw Error('이전 계정의 요청은 서버에서 처리되었습니다. 계정이 변경되어 현재 화면 반영과 후속 작업을 중단했습니다.');
  const current=useWorkLogStore.getState().workLogs.find(w=>w.id===id);
  if(typeof current?.serverRevision==='number'&&typeof log.serverRevision==='number'&&current.serverRevision>log.serverRevision)throw Error('서버 요청은 처리되었습니다. 더 최신 일지가 확인되어 현재 화면 반영과 후속 작업을 중단했습니다.');
 useWorkLogStore.setState(state=>({workLogs:state.workLogs.map(w=>w.id===id?log:w)}));
}
async function markServerRead(id:string,revision:number){
 const actor=useAuthStore.getState().currentUser;
 if(!actor||!id||!Number.isInteger(revision)||revision<1)return false;
 try{
  const result=await studioApi<{ok:boolean}>(`worklogs/${encodeURIComponent(id)}/read`,'POST',{revision});
  return actor===useAuthStore.getState().currentUser&&result.ok===true;
 }catch(error){if(actor!==useAuthStore.getState().currentUser)return false;throw error;}
}
export const useWorkLogStore=create<WorkLogState>((set)=>({
 workLogs:loadInitialWorkLogs(),selectedWorkLogId:null,
 setSelectedWorkLogId:id=>set({selectedWorkLogId:id}),
 saveWorkLog:saveServerLog,
 readWorkLog:markServerRead,
 deleteWorkLog:async id=>{const w=useWorkLogStore.getState().workLogs.find(w=>w.id===id);await studioApi(`worklogs/${encodeURIComponent(id)}`,'DELETE',{revision:w?.serverRevision});set(s=>({workLogs:s.workLogs.filter(w=>w.id!==id),selectedWorkLogId:null}));},
 submitApprovalToLeader:id=>logAction(id,'submit'),submitApprovalToPm:id=>logAction(id,'submit'),
 approveByPm:id=>logAction(id,'review'),approveFinalByChief:id=>logAction(id,'approve'),approveFinalByLeader:id=>logAction(id,'approve'),
 generateItemsFromSchedule:(identifier,date,projects)=>{
  const users=useAuthStore.getState().users;
  const canonical=users.find(u=>u.id===identifier);
  const matches=canonical?[canonical]:users.filter(u=>u.active!==false&&assignmentAliases(u,users).includes(identifier));
  if(!canonical&&matches.length!==1&&users.some(u=>u.name===identifier||String(u.no)===identifier))return [];
  const user=canonical||matches[0],userId=user?.id||identifier;
  return automaticWorkLogItems(assignedItems(userId,date,projects,assignmentAliases(user||{id:userId},users)),date);
 }
}));

export function focusWorkLogsForUser(userId:string){
 const current=useWorkLogStore.getState().workLogs.filter(log=>log.userId===userId);
 const local=loadInitialWorkLogs().filter(log=>log.userId===userId&&!log.serverRevision&&!current.some(item=>item.id===log.id));
 useWorkLogStore.setState({workLogs:[...current,...local],selectedWorkLogId:null});
}
